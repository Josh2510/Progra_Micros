	DEC		VARIABLE_TEMP_2						// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0xFF			// COMPARO CON FF PARA VALIDAR 0
	BRNE	SALIDA_DECREMENTO_HORA
	LDI		VARIABLE_TEMP_2,	0x02			// REINICIO CONTADOR DE DECENAS
	LDI		VARIABLE_TEMP_1,	0x03			// REINICIO CONTADOR DE UNIDADES
