ISR_PCI1:
	PUSH	R16						// Store contents of R16 in stack
	IN		R16,	SREG			// Store SREG in R16
	PUSH	R16						// Store contents of R16 in stack

    SBIS	PINC,	PINC4
	INC		MODO
	CP		MODO,	MAX_MODES
	BRNE	CONTINUAR
	CLR		MODO
CONTINUAR:
	LDI		R16,	2
	CP		MODO,	R16
	BREQ	MOD_RELOJ
	LDI		R16,	3
	CP		MODO,	R16
	BREQ	MOD_FECHA
	LDI		R16,	4
	CP		MODO,	R16
	BREQ	S_ALARMA
MOD_RELOJ:
	LDI		R16,	0x01
	MOV		BANDERA_ACCION,	R16
	RJMP	EXIT_ISR_PCI1

MOD_FECHA:
	LDI		R16,	0x02
	MOV		BANDERA_ACCION,	R16
	RJMP	EXIT_ISR_PCI1

S_ALARMA:
	LDI		R16,	0x04
	MOV		BANDERA_ACCION,	R16
	RJMP	EXIT_ISR_PCI1
	
EXIT_ISR_PCI1:				// MOVEMOS VALORES ACTUALES A VALORES ANTERIORES
	POP		R16						// Get contents from stack and store into R16
	OUT		SREG,	R16				// Load previous contents into SREG
	POP		R16						// Get contents from stack and store into R16
	RETI

ISR_TMR0_OVF:
	PUSH	R16
	IN		R16,	SREG
	PUSH	R16

	LDI		R16,	131						// SE GUARDA EN R16 EL VALOR DE INICIO DEL TIMER
	OUT		TCNT0,	R16						// GUARDA VALORES INICIALES DE TIMER 0 EN TCNT0

	LDI		R16,				0x00
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_1
	LDI		R16,				0x01
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_2
	LDI		R16,				0x02
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_3
	LDI		R16,				0x03
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_4

MULTI_DISPLAY_1:
	LDI		R16,		0x01
	MOV		S_PORT,		R16
	RJMP	FIN
MULTI_DISPLAY_2:
	LDI		R16,		0x02
	MOV		S_PORT,		R16
	RJMP	FIN
MULTI_DISPLAY_3:
	LDI		R16,		0x04
	MOV		S_PORT,		R16
	RJMP	FIN
MULTI_DISPLAY_4:
	LDI		R16,		0x08
	MOV		S_PORT,		R16
	RJMP	FIN

FIN:
	LDI		R16,			0x03
	INC		CONTADOR_MULTI
	AND		CONTADOR_MULTI,	R16
	POP		R16
	OUT		SREG,	R16
	POP		R16
	RETI

ISR_TMR1_OVF:
	PUSH	R16
	IN		R16,	SREG
	PUSH	R16
	// ----------------------------------------------------------------------------------- //
	LDI		R16,	HIGH(TCNT1_value)
	STS		TCNT1H,	R16
	LDI		R16,	LOW(TCNT1_value)
	STS		TCNT1L,	R16
	// ----------------------------------------------------------------------------------- //
	LDI		ZL,		LOW(Cantidad_dias<<1)	// REINICIAMOS PUNTEROS DIAS
	LDI		ZH,		HIGH(Cantidad_dias<<1)
	ADD		ZL,		CONTADOR_MESES
	LPM		VARIABLE_DIAS,	Z
	// ----------------------------------------------------------------------------------- //
	//	LEER DE MEMORIA LOS VALORES DE MINUTOS, HORAS, DIAS Y MESES
	LDS		CONTADOR_M_U,		MOD_MIN_U	
	LDS		CONTADOR_M_D,		MOD_MIN_D
	LDS		CONTADOR_H_U,		MOD_HORA_U
	LDS		CONTADOR_H_D,		MOD_HORA_D
	LDS		CONTADOR_D_U,		MOD_DIA_U
	LDS		CONTADOR_D_D,		MOD_DIA_D
	LDS		CONTADOR_MES_U,		MOD_MES_U
	LDS		CONTADOR_MES_D,		MOD_MES_D
	// ----------------------------------------------------------------------------------- //
	LDI		R16,	0x01
	CP		BANDERA_ESTADO,	R16
	BRNE	REGRESO_1
	// ----------------------------------------------------------------------------------- //
	INC		CONTADOR_TIEMPO					// AUMENTA CONTADOR CADA 100 ms
	CPI		CONTADOR_TIEMPO,	100			// COMPARA CONTADOR CON 10 PARA HACER 1 SEG
	BRNE	REGRESO_1
	CLR		CONTADOR_TIEMPO					// REINICIO DE CONTADOR DE TIEMPO
	
	// ------------------------------------- minutos ------------------------------------- //
	INC		CONTADOR_M_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_M_U,	0x0A			// COMPARO CON 10
	BRNE	REGRESO_1
	CLR		CONTADOR_M_U

	INC		CONTADOR_M_D					// AUMENTO VALOR DE DECENAS
	CPI		CONTADOR_M_D,	0x06			// COMPARO CON 6
	BRNE	REGRESO_1
	CLR		CONTADOR_M_D
	
	// ------------------------------------- HORAS --------------------------------------- //
	CPI		CONTADOR_H_D,	0x02
	BREQ	CONTEO_2_HORAS

CONTEO_1_HORAS:
	INC		CONTADOR_H_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_H_U,	0x0A			// COMPARO CON 10
	BRNE	REGRESO_1
	CLR		CONTADOR_H_U					// REINICIO CONTADOR DE UNIDADES
