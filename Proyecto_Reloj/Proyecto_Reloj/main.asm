	LDS		VARIABLE_TEMP_1,	VALOR_MIN_U	// LEO DE SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_MIN_D

	DEC		VARIABLE_TEMP_1					// DECREMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0xFF		// COMPARO CON FF PARA VALIDAR EL 0
	BRNE	SALIDA_DECREMENTO_MIN			
	LDI		VARIABLE_TEMP_1,	0x09		// REINICIO POR UNDERFLOW

	DEC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0xFF		// COMPARO CON FF PARA VALIDAR EL 0
	BRNE	SALIDA_DECREMENTO_MIN
	LDI		VARIABLE_TEMP_2,	0x05		// REINICIO POR UNDERFLOW
SALIDA_DECREMENTO_MIN:
