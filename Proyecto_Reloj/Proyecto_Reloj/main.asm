	CLR		CONTADOR_MES_D
	LDI		CONTADOR_MES_U,	0x01
	SALIDA_AUMENTO_MES:
	STS		MOD_MES_U,	CONTADOR_MES_U
	STS		MOD_MES_D,	CONTADOR_MES_D
	RET

AUMENTO_MIN_ALARMA:
	LDS		CONTADOR_M_U,	MOD_MIN_U
	LDS		CONTADOR_M_D,	MOD_MIN_D

	INC		CONTADOR_M_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_M_U,	0x0A			// COMPARO CON 10
