	LDI		VARIABLE_TEMP_2,	0x01		// REINICIO DE CONTADOR DE MESES
	LDI		VARIABLE_TEMP_1,	0x02		// REINICIO DE CONTADOR DE MESES
	SALIDA_DECREMENTO_MES:
	STS		VALOR_MES_U,		VARIABLE_TEMP_1	// GUARDA EN SRAM
	STS		VALOR_MES_D,		VARIABLE_TEMP_2
	STS		CONTEO_MESES,		CONTADOR_MESES
	RET
//----------------------------------------------------------------------------------------//
