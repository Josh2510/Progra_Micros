	STS		MOD_MIN_U,			CONTADOR_M_U
	STS		MOD_MIN_D,			CONTADOR_M_D
	STS		MOD_HORA_U,			CONTADOR_H_U
	STS		MOD_HORA_D,			CONTADOR_H_D
