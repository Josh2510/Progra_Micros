	DEC		VARIABLE_TEMP_1						// DECREMENTA UNIDADES
	CPI		VARIABLE_TEMP_1,	0xFF			// COMPARA CON FF PARA VALIDAR EL 0
	BRNE	SALIDA_DECREMENTO_DIA
	LDI		VARIABLE_TEMP_1,	0x09			// CARGA 9 PORQUE DE 20 PASA A 19 Y DE 10 PASA A 09
	DEC		VARIABLE_TEMP_2						// DECREMENTA DECENAS
	RJMP	SALIDA_DECREMENTO_DIA

