	INC		CONTADOR_D_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_D_U,	0x0A			// COMPARO CON 2
	BRNE	REGRESO
	CLR		CONTADOR_D_U
	RJMP	CONTEO_D_DIAS

CONTADOR_2_DIAS:
	LDI		R16,	28
	CP		VARIABLE_DIAS,	R16
	BREQ	CONTEO_2_FEBRERO_DIAS
	INC		CONTADOR_D_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_D_U,	0x0A			// COMPARO CON 10
	BRNE	REGRESO
	CLR		CONTADOR_D_U
	RJMP	CONTEO_D_DIAS
	CONTEO_2_FEBRERO_DIAS:
	INC		CONTADOR_D_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_D_U,	0x09			// COMPARO CON 9
	BRNE	REGRESO
	CLR		CONTADOR_D_U
	RJMP	CONTEO_D_DIAS

CONTADOR_3_DIAS:
	LDI		R16,	31
	CP		VARIABLE_DIAS,	R16
	BREQ	CONTEO_3_1_DIAS
	LDI		R16,	30
	CP		VARIABLE_DIAS,	R16
	BREQ	CONTEO_3_2_DIAS
	CONTEO_3_1_DIAS:
	INC		CONTADOR_D_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_D_U,	0x02			// COMPARO CON 2
	BRNE	REGRESO
	CLR		CONTADOR_D_U
	RJMP	CONTEO_D_DIAS
	CONTEO_3_2_DIAS:
	INC		CONTADOR_D_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_D_U,	0x01			// COMPARO CON 1
	BRNE	REGRESO
	CLR		CONTADOR_D_U
	RJMP	CONTEO_D_DIAS
	
CONTEO_D_DIAS:
	INC		CONTADOR_D_D					// AUMENTO VALOR DE DECENAS
	CPI		CONTADOR_D_D,	0x04			// COMPARO CON 4
	BRNE	REGRESO
	CLR		CONTADOR_D_D
	LDI		CONTADOR_D_U,	0x01

	// ------------------------------------- MESES --------------------------------------- //
	CPI		CONTADOR_MES_D,	0x01
	BREQ	CONTADOR_2_MESES

CONTADOR_1_MESES:
	INC		CONTADOR_MESES
	INC		CONTADOR_MES_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_MES_U,	0x0A			// COMPARO CON 10
	BRNE	REGRESO
	CLR		CONTADOR_MES_U	
	RJMP	CONTEO_D_MESES
CONTADOR_2_MESES:
	INC		CONTADOR_MESES
	INC		CONTADOR_MES_U					// AUMENTO VALOR DE UNIDADES
	CPI		CONTADOR_MES_U,	0x03			// COMPARO CON 2
	BRNE	REGRESO
	LDI		CONTADOR_MES_U,	0x01
	MOV		CONTADOR_MESES,	CONTADOR_MES_U
	RJMP	CONTEO_D_MESES

