// Encabezado (Definici?n de Registros, Variables y Constantes)
.include "M328PDEF.inc"     // Include definitions specific to ATMega328P
.dseg
.org    SRAM_START
.equ	TCNT1_value = 0x0BDC
/****************************************/
//	Variables en SRAM
.dseg						// VARIABLE DENTRO DE SRAM
VALOR_MIN_U:		.byte   1   // VARIABLES DE MODIFICACION DE MINUTOS
VALOR_MIN_D:		.byte   1
VALOR_HORA_U:		.byte   1	// VARIABLES DE MODIFICACION DE HORAS
VALOR_HORA_D:		.byte   1
VALOR_DIA_U:		.byte	1	// VARIABLES DE MODIFICACION DE DIAS
VALOR_DIA_D:		.byte	1
VALOR_MES_U:		.byte	1	// VARIABLES DE MODIFICACION DE MESES
VALOR_MES_D:		.byte	1
A_MIN_U:			.byte	1	// VARIABLES DE MINUTOS PARA ALARMA
A_MIN_D:			.byte	1	
A_HORA_U:			.byte	1	// VARIABLES DE HORAS PARA ALARMA
A_HORA_D:			.byte	1
CONTEO_MESES:		.byte	1	// CONTADOR DE MESES PARA TABLA DE CANTIDAD DE DIAS
/****************************************/
//	CODIGO
.cseg
.org	0x0000
	JMP	START
.org	PCI1addr
	JMP	ISR_PCI1
.org	OVF1addr
	JMP	ISR_TMR1_OVF
.org	OVF0addr
	JMP	ISR_TMR0_OVF
// REGISTROS DEFINIDOS PARA VARIABLES ESPECIFICAS
.def	VALOR_C_ANTERIOR =		R0				// VALORES DE PINC DEL INICIO DEL PROGRAMA Y PARA HACER QUE FUNCIONEN BOTONES POR SEPARADO
.def	S_PORT =				R1				// SALIDA A PORTB
.def	CONTADOR_MULTI =		R2				// CONTADOR PARA MULTIPLEXADO
.def	MODO =					R3				// REGISTRO DE MODO
.def	MAX_MODES =				R5				// VALOR MAXIMO DE MODOS
.def	CONTADOR_MESES =		R6				// CONTADOR DE MES PARA DETERMINAR MAXIMO DE DIAS
.def	VARIABLE_DIAS =			R7				// VARIABLE QUE RECIBE EL MAXIMO DE DIAS
.def	VALOR_C_ACTUAL =		R10				// LECTURA ACTUAL DEL PINC
.def	ENTRADA_PINC =			R13				// REGISTRO PARA GUARDAR VALORES ACTUALES DE PINC
.def	REG_DISPLAY =			R14				// REGISTRO DE SALIDA PARA DISPLAYS
.def	S_DISPLAY =				R15				// SALIDA PARA DISPLAYS
.def	VARIABLE_TEMP_1 =		R17				// VARIABLES TEMPORALES
.def	VARIABLE_TEMP_2 =		R18				
.def	CONTADOR_TIEMPO =		R19				// CONTADOR DE TIEMPO PARA TIMER 1
.def	CONTADOR_ESTADO =		R20				// CONTADOR DE ESTADOS PARA INDICAR EN LEDS
.def	BANDERA_ACCION =		R21				// BANDERA DE ACCIONES
.def	BANDERA_ESTADO =		R22				// BANDERA DE ESTADOS
.def	PARPADEO_LED =			R23				// REGISTRO PARA PARPADEO DE LEDS

START:
 /****************************************/
// Configuraci?n de la pila
	LDI     R16, LOW(RAMEND)
	OUT     SPL, R16
	LDI     R16, HIGH(RAMEND)
	OUT     SPH, R16
/****************************************/
// CREACION DE TABLA PARA DISPLAY
Numero: .db 0x40, 0x79, 0x24, 0x30, 0x19, 0x12, 0x02, 0x78, 0x00, 0x10, 0x08, 0x03, 0x70, 0x21, 0x06, 0x0E
Cantidad_dias:	.db	0x00, 0x1F, 0x1C, 0x1F, 0x1E, 0x1F, 0x1E, 0x1F, 0x1F, 0x1E, 0x1F, 0x1E, 0x1F, 0x00
/****************************************/
// Configuracion MCU
SETUP:
    CLI									// DESHABILITAR INTERRUPCIONES GLOBALES
	// PRESCALER
	LDI		R16,	(1 << CLKPCE)
	STS		CLKPR,	R16					// HABILITAR CAMBIOS EN CLOCK PRINCIPAL PARA HABILITAR PRESCALER
	LDI		R16,	(1 << CLKPS2)
	STS		CLKPR,	R16					// CAMBIAR FRECUENCIA DE 16 MHz a 1MHz

	// TIMER
	CALL INIT_TMR0						// LLAMAR A INICIALIZACION DE TIMER
	CALL INIT_TMR1						//

    // ENTRADAS
	LDI		R16,	0x20			
	OUT		DDRC,	R16					// PONER EN ENTRADAS LOS BITS 0, 1, 2, 3 Y 4 DE PORTC
	LDI		R16,	0x1F				// VALOR PARA ACTIVAR PULL UPS
	OUT		PORTC,	R16					// HABILITAR PULL UPS EN PINC

	// SALIDAS
	LDI		R16,	0xFF				
	OUT		DDRB,	R16					// PONER EN SALIDAS LOS BITS DE PORTB
	OUT		DDRD,	R16					// PONER EN SALIDAS LOS BITS DE PORTD  

	LDI		R16,	0xFF
	OUT		PORTB,	R16					// PONER DE VALOR INICIAL PARA PORTB 0

		// DISPLAYS DE 7 SEGMENTOS
	LDI		ZL,		LOW(Numero<<1)		// INICIALIZAR PUNTERO Z
	LDI		ZH,		HIGH(Numero<<1)		//
	LPM		R16,	Z					// 
	OUT		PORTD,	R16					// PONER DE VALOR INICIAL PARA PORTD 0

	// HABILITACION DE INTERRUPCIONES
	LDI		R16,	(1 << PCIE1)		
    STS		PCICR,	R16					// HABILITA INTERRUPCIONES EN PORTC
    LDI		R16,	(1 << PCINT8) | (1 << PCINT9) | (1 << PCINT10) | (1 << PCINT11) | (1 << PCINT12)
    STS		PCMSK1, R16					// HABILITAR INTERRUPCIONES PARA BITS 0 A 4 DE PINC
	LDI		R16,	(1 << TOIE0)		// HABILITAR INTERRUPCIONES DE TIMER0
	STS		TIMSK0,	R16
	LDI		R16,	(1 << TOIE1)		// HABILITAR INTERRUPCIONES DE TIMER1
	STS		TIMSK1,	R16

	// VARIABLES A USAR
	IN		VALOR_C_ANTERIOR,	PINC		// VALORES DE PIN C
	LDI		R16,				0x00
	STS		VALOR_MIN_U,		R16			// REINICIAR VALORES DE VARIABLES
	STS		VALOR_MIN_D,		R16
	STS		VALOR_HORA_U,		R16
	STS		VALOR_HORA_D,		R16
	STS		VALOR_DIA_D,		R16
	STS		VALOR_MES_D,		R16
	STS		A_MIN_U,			R16
	STS		A_MIN_D,			R16
	STS		A_HORA_U,			R16
	STS		A_HORA_D,			R16
	MOV		CONTADOR_MULTI,		R16			// REINICIAR VALORES EN CONTADOR PARA MULTIPLEXADO
	LDI		R16,				0x01
	STS		VALOR_DIA_U,		R16
	STS		VALOR_MES_U,		R16
	STS		CONTEO_MESES,		R16
	LDI		R16,				5
	MOV		MAX_MODES,			R16	
	LDI		PARPADEO_LED,		0x80				
	CLR		VARIABLE_TEMP_1					// REINICIAR VARIABLES TEMPORALES
	CLR		VARIABLE_TEMP_2					
	CLR		CONTADOR_TIEMPO					// CONTADOR PARA TIEMPO
	CLR		REG_DISPLAY						// REGISTRO DONDE SE GUARDA VALOR QUE VA A SALIR A DISPLAY
	CLR		CONTADOR_ESTADO					// REINICIAR CONTADOR DE ESTADO
	CLR		BANDERA_ACCION					// REINICIAR BANDERAS
	CLR		BANDERA_ESTADO					//

	SEI										// HABILITAR INTERRUPCIONES GLOBALES
/****************************************/
// Loop Infinito
MAIN_LOOP:
	// ----------------------------------------------------------------------------------- //
	SBRC	BANDERA_ESTADO,		3			// COMPROBAR SI BANDERA DE SONAR BUZZER ESTA ENCENDIDA
	CALL	BUZZER
	// ----------------------------------------------------------------------------------- //
	LDI		R16,	0						// VERIFICAR EN QUE MODO ESTA
	CP		MODO,	R16
	BREQ	RELOJ
	LDI		R16,	1
	CP		MODO,	R16
	BREQ	FECHA
	LDI		R16,	2
	CP		MODO,	R16
	BREQ	MODIFICAR_RELOJ
	LDI		R16,	3
	CP		MODO,	R16
	BREQ	MODIFICAR_FECHA
	LDI		R16,	4
	CP		MODO,	R16
	BREQ	SET_ALARMA

RELOJ:
	SBR		BANDERA_ESTADO,	(1<<0)			// ENCENDER BIT 0 DE BANDERA ESTADO
	CBR		BANDERA_ESTADO,	(1<<1)			// APAGAR BIT 1 DE BANDERA DE ESTADO
	LDI		CONTADOR_ESTADO,	0x00		// CARGAR VALOR DE ESTADO PARA MOSTRAR EN LEDS
	CALL	SALIDA_DISPLAY_HORA
	RJMP	REGRESO_MAIN
FECHA:
	SBR		BANDERA_ESTADO,	(1<<0)			// ENCENDER BIT 0 DE BANDERA DE ESTADO
	CBR		BANDERA_ESTADO,	(1<<1)			// APAGAR BIT 1 DE BANDERA DE ESTADO
	LDI		CONTADOR_ESTADO,	0x01		// CARGAR VALOR DE ESTADO PARA MOSTRAR EN LEDS
	CALL	SALIDA_DISPLAY_FECHA
	RJMP	REGRESO_MAIN
MODIFICAR_RELOJ:
	SBR		BANDERA_ESTADO,	(1<<1)			// ENCENDER BIT 1 DE BANDERA DE ESTADO
	CBR		BANDERA_ESTADO,	(1<<0)			// APAGAR BIT 0 DE BANDERA DE ESTADO
	LDI		CONTADOR_ESTADO,	0x02		// CARGAR VALOR DE ESTADO PARA MOSTRAR EN LEDS
	CALL	CAMBIAR_RELOJ
	CALL	SALIDA_DISPLAY_HORA
	RJMP	REGRESO_MAIN
MODIFICAR_FECHA:
	SBR		BANDERA_ESTADO,	(1<<1)			// ENCENDER BIT 1 DE BANDERA DE ESTADO
	CBR		BANDERA_ESTADO,	(1<<0)			// APAGAR BIT 0 DE BANDERA DE ESTADO
	LDI		CONTADOR_ESTADO,	0x03		// CARGAR VALOR DE ESTADO PARA MOSTRAR EN LEDS
	CALL	CAMBIAR_FECHA
	CALL	SALIDA_DISPLAY_FECHA
	RJMP	REGRESO_MAIN
SET_ALARMA:
	SBR		BANDERA_ESTADO,	(1<<0)			// ENCENDER BIT 0 DE BANDERA DE ESTADO
	CBR		BANDERA_ESTADO,	(1<<1)			// APAGAR BIT 1 DE BANDERA DE ESTADO
	LDI		CONTADOR_ESTADO,	0x00		// CARGAR VALOR DE ESTADO PARA MOSTRAR EN LEDS
	CALL	SETEAR_ALARMA
	CALL	SALIDA_DISPLAY_ALARMA
	RJMP	REGRESO_MAIN
REGRESO_MAIN:
    RJMP    MAIN_LOOP

/****************************************/
// NON-Interrupt subroutines
INIT_TMR0:
	LDI		R16,	(1 << CS01)			// CONFIGURANDO PRESCALER DE I/O A 8
	OUT		TCCR0B,	R16
	LDI		R16,	131					// SE GUARDA EN R16 EL VALOR DE INICIO DEL TIMER
	OUT		TCNT0,	R16					// GUARDA VALORES INICIALES DE TIMER 0 EN TCNT0
	RET
//----------------------------------------------------------------------------------------//
INIT_TMR1:
	LDI		R16,	0x00
	STS		TCCR1A,	R16
	LDI		R16,	(1 << CS11)			// CONFIGURAR PRESCALER DE I/O A 8
	STS		TCCR1B,	R16
	LDI		R16,	HIGH(TCNT1_value)	// CARGAR EN R16 LA PARTE SUPERIOR DEL VALOR INICIAL DEL TIMER
	STS		TCNT1H,	R16
	LDI		R16,	LOW(TCNT1_value)	// CARGAR EN R16 LA PARTE INFERIOR DEL VALOR INICIAL DEL TIMER
	STS		TCNT1L,	R16
	RET
//----------------------------------------------------------------------------------------//
SALIDA_DISPLAY_HORA:
	CLR		S_DISPLAY
	OUT		PORTB,		S_PORT				// MANDAMOS REGISTRO A PORTB

	SBRC	S_PORT,	0						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_MIN_U		// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	1						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_MIN_D		// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY
	
	SBRC	S_PORT,	2						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_HORA_U	// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	3						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_HORA_D	// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY

	LDI		ZL,		LOW(Numero<<1)			// REINICIAMOS PUNTEROS
	LDI		ZH,		HIGH(Numero<<1)			//
	ADD		ZL,		REG_DISPLAY				// SUMAMOS A PARTE BAJA DE PUNTERO CONTADOR DE DISPLAY
	LPM		S_DISPLAY,	Z					// MANDAMOS VALOR DE Z A REGISTRO DE SALIDA
	OR		S_DISPLAY,	PARPADEO_LED
	OUT		PORTD,	S_DISPLAY
	RET
//----------------------------------------------------------------------------------------//
SALIDA_DISPLAY_FECHA:
	CLR		S_DISPLAY
	OUT		PORTB,		S_PORT				// MANDAMOS REGISTRO A PORTB

	SBRC	S_PORT,	0						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_MES_U		// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	1						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_MES_D		// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY
	
	SBRC	S_PORT,	2						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_DIA_U		// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	3						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	VALOR_DIA_D		// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY

	LDI		ZL,		LOW(Numero<<1)			// REINICIAMOS PUNTEROS
	LDI		ZH,		HIGH(Numero<<1)			//
	ADD		ZL,		REG_DISPLAY				// SUMAMOS A PARTE BAJA DE PUNTERO CONTADOR DE DISPLAY
	LPM		S_DISPLAY,	Z					// MANDAMOS VALOR DE Z A REGISTRO DE SALIDA
	OR		S_DISPLAY,	PARPADEO_LED
	OUT		PORTD,	S_DISPLAY
	RET
//----------------------------------------------------------------------------------------//
SALIDA_DISPLAY_ALARMA:
	SBRC	BANDERA_ESTADO,	4				// VERIFICAR SI BANDERA DE PARPADEO DE ALARMA ESTA ACTIVADO
	RET

	CLR		S_DISPLAY
	OUT		PORTB,		S_PORT				// MANDAMOS REGISTRO A PORTB

	SBRC	S_PORT,	0						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	A_MIN_U			// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	1						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	A_MIN_D			// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY
	
	SBRC	S_PORT,	2						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	A_HORA_U		// MOVER VALOR DE UNIDADES A REGISTRO DE DISPLAY

	SBRC	S_PORT,	3						// SKIP IF BIT IN REGISTER IS SET
	LDS		REG_DISPLAY,	A_HORA_D		// MOVER VALOR DE DECENAS A REGISTRO DE DISPLAY

	LDI		ZL,			LOW(Numero<<1)		// REINICIAMOS PUNTEROS
	LDI		ZH,			HIGH(Numero<<1)			
	ADD		ZL,			REG_DISPLAY			// SUMAMOS A PARTE BAJA DE PUNTERO CONTADOR DE DISPLAY
	LPM		S_DISPLAY,	Z					// MANDAMOS VALOR DE Z A REGISTRO DE SALIDA
	OR		S_DISPLAY,	PARPADEO_LED
	OUT		PORTD,		S_DISPLAY
	RET
//----------------------------------------------------------------------------------------//
CAMBIAR_RELOJ:
	IN		ENTRADA_PINC,		PINC				// SE LEE EL PIN C
	MOV		VALOR_C_ACTUAL,		ENTRADA_PINC		// MOVEMOS REGISTRO R16 A R5
	EOR		VALOR_C_ACTUAL,		VALOR_C_ANTERIOR	// XOR ENTRE VALORES ACTUALES Y VALORES ANTERIORES
	MOV		VALOR_C_ANTERIOR,	ENTRADA_PINC		// MOVEMOS VALORES ACTUALES A VALORES ANTERIORES

	SBRC	VALOR_C_ACTUAL,		0					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_0
	SBRC	VALOR_C_ACTUAL,		1					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_1
	SBRC	VALOR_C_ACTUAL,		2					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_2
	SBRC	VALOR_C_ACTUAL,		3					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_3
	RET
//----------------------------------------------------------------------------------------//
CAMBIAR_FECHA:
	IN		ENTRADA_PINC,		PINC				// SE LEE EL PIN C
	MOV		VALOR_C_ACTUAL,		ENTRADA_PINC		// MOVEMOS REGISTRO R16 A R5
	EOR		VALOR_C_ACTUAL,		VALOR_C_ANTERIOR	// XOR ENTRE VALORES ACTUALES Y VALORES ANTERIORES
	MOV		VALOR_C_ANTERIOR,	ENTRADA_PINC		// MOVEMOS VALORES ACTUALES A VALORES ANTERIORES

	SBRC	VALOR_C_ACTUAL,		0					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_0
	SBRC	VALOR_C_ACTUAL,		1					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_1
	SBRC	VALOR_C_ACTUAL,		2					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_2
	SBRC	VALOR_C_ACTUAL,		3					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_3
	RET
//----------------------------------------------------------------------------------------//
SETEAR_ALARMA:
	IN		ENTRADA_PINC,		PINC				// SE LEE EL PIN C
	MOV		VALOR_C_ACTUAL,		ENTRADA_PINC		// MOVEMOS REGISTRO R16 A R5
	EOR		VALOR_C_ACTUAL,		VALOR_C_ANTERIOR	// XOR ENTRE VALORES ACTUALES Y VALORES ANTERIORES
	MOV		VALOR_C_ANTERIOR,	ENTRADA_PINC		// MOVEMOS VALORES ACTUALES A VALORES ANTERIORES

	SBRC	VALOR_C_ACTUAL,		0					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_0
	SBRC	VALOR_C_ACTUAL,		1					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_1
	SBRC	VALOR_C_ACTUAL,		2					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_2
	SBRC	VALOR_C_ACTUAL,		3					// SKIP IF BIT IN REGISTER IS CLEAR
	CALL	BIT_3
	RET
//----------------------------------------------------------------------------------------//
BIT_0:
	SBRC	BANDERA_ACCION,	0				// COMPRUEBA QUE BIT ESTA ENCENDIDO
	RJMP	AU_HORA							// PARA HACER LA INSTRUCCION CORRECTA
	SBRC	BANDERA_ACCION,	1
	RJMP	AU_DIA
	SBRC	BANDERA_ACCION,	2
	RJMP	AU_HORA_ALARMA
	RJMP	SALIDA_BIT_0
AU_HORA:
	SBRS	ENTRADA_PINC,	0				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_HORA
	RJMP	SALIDA_BIT_0
AU_DIA:
	SBRS	ENTRADA_PINC,	0				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_DIA
	RJMP	SALIDA_BIT_0
AU_HORA_ALARMA:
	SBRS	ENTRADA_PINC,	0				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_HORA_ALARMA
	RJMP	SALIDA_BIT_0
SALIDA_BIT_0:
	RET
//----------------------------------------------------------------------------------------//
BIT_1:
	SBRC	BANDERA_ACCION,	0				// COMPRUEBA QUE BIT ESTA ENCENDIDO
	RJMP	DE_HORA							// PARA HACER LA INSTRUCCION CORRECTA
	SBRC	BANDERA_ACCION,	1
	RJMP	DE_DIA
	SBRC	BANDERA_ACCION,	2
	RJMP	DE_HORA_ALARMA
	RJMP	SALIDA_BIT_1
DE_HORA:
	SBRS	ENTRADA_PINC,	1				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_HORA
	RJMP	SALIDA_BIT_0
DE_DIA:
	SBRS	ENTRADA_PINC,	1				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_DIA
	RJMP	SALIDA_BIT_0
DE_HORA_ALARMA:
	SBRS	ENTRADA_PINC,	1				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_HORA_ALARMA
	RJMP	SALIDA_BIT_0
SALIDA_BIT_1:
	RET
//----------------------------------------------------------------------------------------//
BIT_2:
	SBRC	BANDERA_ACCION,	0				// COMPRUEBA QUE BIT ESTA ENCENDIDO
	RJMP	AU_MIN							// PARA HACER LA INSTRUCCION CORRECTA
	SBRC	BANDERA_ACCION,	1
	RJMP	AU_MES
	SBRC	BANDERA_ACCION,	2
	RJMP	AU_MIN_ALARMA
	RJMP	SALIDA_BIT_2
AU_MIN:
	SBRS	ENTRADA_PINC,	2				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_MIN
	RJMP	SALIDA_BIT_2
AU_MES:
	SBRS	ENTRADA_PINC,	2				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_MES
	RJMP	SALIDA_BIT_2
AU_MIN_ALARMA:
	SBRS	ENTRADA_PINC,	2				// SKIP IF BIT IN REGISTER IS SET
	CALL	AUMENTO_MIN_ALARMA
	RJMP	SALIDA_BIT_2
SALIDA_BIT_2:
	RET
//----------------------------------------------------------------------------------------//
BIT_3:
	SBRC	BANDERA_ACCION,	0				// COMPRUEBA QUE BIT ESTA ENCENDIDO
	RJMP	DE_MIN							// PARA HACER LA INSTRUCCION CORRECTA
	SBRC	BANDERA_ACCION,	1
	RJMP	DE_MES
	SBRC	BANDERA_ACCION,	2
	RJMP	DE_MIN_ALARMA
	RJMP	SALIDA_BIT_3
DE_MIN:
	SBRS	ENTRADA_PINC,	3				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_MIN
	RJMP	SALIDA_BIT_3
DE_MES:
	SBRS	ENTRADA_PINC,	3				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_MES
	RJMP	SALIDA_BIT_3
DE_MIN_ALARMA:
	SBRS	ENTRADA_PINC,	3				// SKIP IF BIT IN REGISTER IS SET
	CALL	DISMINUYE_MIN_ALARMA
	RJMP	SALIDA_BIT_3
SALIDA_BIT_3:
	RET
//----------------------------------------------------------------------------------------//
AUMENTO_MIN:
	LDS		VARIABLE_TEMP_1,	VALOR_MIN_U	// CARGAR VALORES DESDE LA SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_MIN_D

	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	SALIDA_AUMENTO_MIN
	CLR		VARIABLE_TEMP_1

	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x06		// COMPARO CON 6
	BRNE	SALIDA_AUMENTO_MIN
	CLR		VARIABLE_TEMP_2
SALIDA_AUMENTO_MIN:
	STS		VALOR_MIN_U,	VARIABLE_TEMP_1	// GUARDAR VALORES EN LA SRAM
	STS		VALOR_MIN_D,	VARIABLE_TEMP_2
	RET
//----------------------------------------------------------------------------------------//
AUMENTO_HORA:
	LDS		VARIABLE_TEMP_1,	VALOR_HORA_U	// CARGAR VALORES DESDE LA SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_HORA_D
	CPI		VARIABLE_TEMP_2,	0x02
	BREQ	C_2_HORAS

	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	SALIDA_AUMENTO_HORA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	RJMP	C_D_HORAS

C_2_HORAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x04		// COMPARO CON 4
	BRNE	SALIDA_AUMENTO_HORA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	RJMP	C_D_HORAS

C_D_HORAS:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x03		// COMPARO CON 6
	BRNE	SALIDA_AUMENTO_HORA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE DECENAS
	CLR		VARIABLE_TEMP_2					// REINICIO CONTADOR DE UNIDADES
SALIDA_AUMENTO_HORA:
	STS		VALOR_HORA_U,	VARIABLE_TEMP_1	// GUARDAR VALORES EN LA SRAM
	STS		VALOR_HORA_D,	VARIABLE_TEMP_2				
	RET
//----------------------------------------------------------------------------------------//
AUMENTO_DIA:
	LDS		VARIABLE_TEMP_1,	VALOR_DIA_U	// CARGAR VALORES DESDE LA SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_DIA_D
	LDS		CONTADOR_MESES,		CONTEO_MESES

	LDI		ZL,		LOW(Cantidad_dias<<1)	// REINICIAMOS PUNTEROS DIAS
	LDI		ZH,		HIGH(Cantidad_dias<<1)
	ADD		ZL,		CONTADOR_MESES
	LPM		VARIABLE_DIAS,	Z

	CPI		VARIABLE_TEMP_2,	0x03		// COMPROBAMOS SI DECENAS DE DIA ES 3
	BREQ	C_3_DIAS						// PARA COMPROBAR SI EL MAXIMO DE DIAS ES 30 O 31
	CPI		VARIABLE_TEMP_2,	0x02		// COMPROBAMOS SI DECENAS EN DIA ES 2
	BREQ	C_2_DIAS						// PARA COMPROBAR SI EL MAXIMO DE DIAS ES 28

	C_1_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 2
	BRNE	SALIDA_AUMENTO_DIA					
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW
	RJMP	C_D_DIAS

	C_2_DIAS:
	LDI		R16,	28
	CP		VARIABLE_DIAS,	R16				// COMPRUEBO SI EL MAXIMO ES 28
	BREQ	C_2_FEBRERO_DIAS				// SI ES ASI SALTO A CONTADOR DE FEBRERO, SI NO CONTINUO NORMAL
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	SALIDA_AUMENTO_DIA
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW
	RJMP	C_D_DIAS
	C_2_FEBRERO_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x09		// COMPARO CON 9
	BRNE	SALIDA_AUMENTO_DIA
	CLR		VARIABLE_TEMP_2					// LIMPIAMOS VARIABLE DE DECENAS
    LDI		VARIABLE_TEMP_1, 0x01			// REINICIAMOS CONTADOR DE DIAS
    RJMP	SALIDA_AUMENTO_DIA				// SALTAMOS DIRECTAMENTE A LA SALIDA

	C_3_DIAS:
	LDI		R16,	31						// COMPRUEBA SI EL MAXIMO ES 31 DIAS
	CP		VARIABLE_DIAS,	R16
	BREQ	C_3_1_DIAS						
	LDI		R16,	30						// COMPRUEBA SI EL MAXIMO ES 30 DIAS
	CP		VARIABLE_DIAS,	R16		
	BREQ	C_3_2_DIAS
	C_3_1_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x02		// COMPARO CON 2
	BRNE	SALIDA_AUMENTO_DIA
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW
	RJMP	C_D_DIAS
	C_3_2_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x01		// COMPARO CON 1
	BRNE	SALIDA_AUMENTO_DIA
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW
	RJMP	C_D_DIAS
	
	C_D_DIAS:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x04		// COMPARO CON 4
	BRNE	SALIDA_AUMENTO_DIA
	CLR		VARIABLE_TEMP_2					// REINICIO POR OVERFLOW
	LDI		VARIABLE_TEMP_1,	0x01		// REINICIO POR OVERFLOW
SALIDA_AUMENTO_DIA:
	STS		VALOR_DIA_U,	VARIABLE_TEMP_1	// GUARDAR VALORES EN LA SRAM
	STS		VALOR_DIA_D,	VARIABLE_TEMP_2
	RET
//----------------------------------------------------------------------------------------//
AUMENTO_MES:
	LDS		VARIABLE_TEMP_1,	VALOR_MES_U	// CARGAR VALORES DESDE LA SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_MES_D
	LDS		CONTADOR_MESES,		CONTEO_MESES
	
	LDI		ZL,		LOW(Cantidad_dias<<1)	// REINICIAMOS PUNTEROS DIAS
	LDI		ZH,		HIGH(Cantidad_dias<<1)
	ADD		ZL,		CONTADOR_MESES
	LPM		VARIABLE_DIAS,	Z

	CPI		VARIABLE_TEMP_2,	0x01		// COMPROBAMOS DECENAS PARA VER SI SALTADOS
	BREQ	C_2_MESES						// A MESES 10, 11 Y 12

	C_1_MESES:
	INC		CONTADOR_MESES					// AUMENTA CONTADOR DE MESES
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A			// COMPARO CON 10
	BRNE	SALIDA_AUMENTO_MES
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW
	RJMP	C_D_MESES
	C_2_MESES:
	INC		CONTADOR_MESES					// AUMENTA CONTADOR DE MESES
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x03		// COMPARO CON 3
	BRNE	SALIDA_AUMENTO_MES
	LDI		VARIABLE_TEMP_1,	0x01		// REINICIAR VALORES DESPUES DE OVERFLOW
	LDI		R16,			0x01			// REINICIO DE CONTADOR DE MESES POR OVERFLOW
	MOV		CONTADOR_MESES,	R16
	RJMP	C_D_MESES

	C_D_MESES:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x02		// COMPARO CON 2
	BRNE	SALIDA_AUMENTO_MES
	CLR		VARIABLE_TEMP_2					// REINICIO DE CONTADOR DE MESES
	LDI		VARIABLE_TEMP_1,	0x01		// REINICIO DE CONTADOR DE MESES
	SALIDA_AUMENTO_MES:
	STS		VALOR_MES_U,	VARIABLE_TEMP_1	// GUARDO VALORES EN SRAM
	STS		VALOR_MES_D,	VARIABLE_TEMP_2
	STS		CONTEO_MESES,	CONTADOR_MESES
	RET
