	INC		CONTADOR_MES_D					// AUMENTO VALOR DE DECENAS
	CPI		CONTADOR_MES_D,	0x02			// COMPARO CON 2
	BRNE	REGRESO
	CLR		CONTADOR_MES_D
	LDI		CONTADOR_MES_U,	0x01
	CLR		CONTADOR_D_D
	LDI		CONTADOR_D_U,	0x01
	CLR		CONTADOR_H_D
	CLR		CONTADOR_H_U
	CLR		CONTADOR_M_D
	CLR		CONTADOR_M_U
