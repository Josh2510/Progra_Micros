	LDI		R16,				28				// COMPRUEBA SI EL MAXIMO DE DIAS ES 28
	CP		VARIABLE_DIAS,		R16				// SI ASI ES, SALTA A FEBRERO
	BREQ	FEBRERO
	LDI		R16,				30				// COMPRUEBA SI EL MAXIMO DE DIAS ES 30
	CP		VARIABLE_DIAS,		R16				// SI ES ASI, SALTA A 30 DIAS
	BREQ	DIAS_30

	LDI		VARIABLE_TEMP_1,	0x01			// SI NO SIGUE A 31 DIAS Y CARGA LOS VALORES CORRESPONDIENTES
	LDI		VARIABLE_TEMP_2,	0x03
	RJMP	SALIDA_DECREMENTO_DIA
	DIAS_30:
	LDI		VARIABLE_TEMP_1,	0x00
	LDI		VARIABLE_TEMP_2,	0x03
	RJMP	SALIDA_DECREMENTO_DIA
	FEBRERO:
	LDI		VARIABLE_TEMP_1,	0x08
	LDI		VARIABLE_TEMP_2,	0x02
	RJMP	SALIDA_DECREMENTO_DIA


