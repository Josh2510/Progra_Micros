// Interrupt routines
ISR_PCI1:
	PUSH	R16						// Store contents of R16 in stack
	IN		R16,	SREG			// Store SREG in R16
	PUSH	R16						// Store contents of R16 in stack

    SBIS	PINC,	PINC4			// REVISA SI LA INTERRUPCION FUE POR EL BIT 4 QUE CAMBIA MODO
	INC		MODO					// SI FUE POR BIT 4 AUMENTA EL MODO
	SBRC	BANDERA_ESTADO,	3		// AQUI REVISA POR LA BANDERA DE BUZZER ACTIVADO
	CBR		BANDERA_ESTADO,	(1<<3)	// SI ESTA ACTIVADA, APAGA LA BANDERA Y LUEGO APAGA EL BUZZER
	CP		MODO,	MAX_MODES		// COMPRUEBA CON EL MAXIMO DE MODOS
	BRNE	CONTINUAR
	CLR		MODO					// REINICIA POR OVERFLOW
CONTINUAR:
	LDI		R16,	2				// AQUI REVISA EN QUE MODO ESTA PARA ACTIVAR EL BIT DE LA BANDERA DE ACCION
	CP		MODO,	R16
	BREQ	MOD_RELOJ
	LDI		R16,	3
	CP		MODO,	R16
	BREQ	MOD_FECHA
	LDI		R16,	4
	CP		MODO,	R16
	BREQ	S_ALARMA
	RJMP	FINAL					// SI NO SE CUMPLE NINGUNO, SALTA HASTA EL FINAL
MOD_RELOJ:
	SBR		BANDERA_ACCION,	(1<<0)				// ACTIVA EL BIT 0 Y APAGA LOS DEMAS
	CBR		BANDERA_ACCION,	(1<<1) | (1<<2)
	RJMP	FINAL

MOD_FECHA:
	SBR		BANDERA_ACCION,	(1<<1)				// ACTIVA EL BIT 1 Y APAGA LOS DEMAS
	CBR		BANDERA_ACCION,	(1<<2) | (1<<0)
	RJMP	FINAL

S_ALARMA:
	SBR		BANDERA_ACCION,	(1<<2)				// ACTIVA EL BIT 2 Y APAGA LOS DEMAS
	CBR		BANDERA_ACCION,	(1<<1) | (1<<0)
	RJMP	FINAL
	
FINAL:
	LDI		R16,	0				// AQUI REVISA SI EL MODO AL QUE CAMBIO ES 0, YA QUE SIGNIFICA QUE CAMBIO DE SETEAR ALARMA A MODO RELOJ
	CP		MODO,	R16
	BRNE	EXIT_ISR_PCI1
	SBR		BANDERA_ESTADO,	(1<<2)	// POR LO QUE ACTIVA LA BANDERA DE ALARMA CONFIGURADA
EXIT_ISR_PCI1:		
	SBRS	BANDERA_ESTADO,	3		// AQUI REVISA SI LA BANDERA DE BUZZER ESTA ENCENDIDA Y LA APAGA SI ES VERDAD.
	CBI		PORTC,	PINC5
	POP		R16						// Get contents from stack and store into R16
	OUT		SREG,	R16				// Load previous contents into SREG
	POP		R16						// Get contents from stack and store into R16
	RETI
//----------------------------------------------------------------------------------------//
ISR_TMR0_OVF:
	PUSH	R16
	IN		R16,	SREG
	PUSH	R16

	LDI		R16,				131				// SE GUARDA EN R16 EL VALOR DE INICIO DEL TIMER
	OUT		TCNT0,				R16				// GUARDA VALORES INICIALES DE TIMER 0 EN TCNT0

	SBRC	BANDERA_ESTADO,		4				// REVISA BANDERA PARA APAGAR MULTIPLEXADO
	RJMP	APAGAR_DISPLAYS

	SWAP	CONTADOR_ESTADO						// AQUI HACE SWAP CON EL REGISTRO DE CONTADOR DE ESTADOS QUE TIENE QUE LEDS SE ENCIENDEN
	LDI		R16,				0x00			// LO QUE HACE QUE PASE HA SER LOS PRIMEROS 4 BITS
	CP		CONTADOR_MULTI,		R16				// AQUI REVISA EL CONTADOR DEL MULTIPLEXADO
	BREQ	MULTI_DISPLAY_1						// PARA MANDAR A ACTIVAR LOS DIFERENTES TRANSISTORES
	LDI		R16,				0x01
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_2
	LDI		R16,				0x02
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_3
	LDI		R16,				0x03
	CP		CONTADOR_MULTI,		R16
	BREQ	MULTI_DISPLAY_4

MULTI_DISPLAY_1:
	LDI		R16,		0x01					// AQUI CARGA EL VALOR PARA ENCENDER EL TRANSISTOR CORRESPONDIENTE
	OR		CONTADOR_ESTADO,	R16				// HACE UN OR CON EL CONTADOR DE ESTADOS PARA AGREGAR SUS BITS
	MOV		S_PORT,		CONTADOR_ESTADO			// Y LO MANDA A S_PORT PARA QUE SALGA EN LAS SALIDAS DE DISPLAY
	RJMP	FIN
MULTI_DISPLAY_2:
	LDI		R16,		0x02					// AQUI SUCEDE LO MISMO QUE ARRIBA, PERO CON OTRO TRANSISTOR
	OR		CONTADOR_ESTADO,	R16
	MOV		S_PORT,		CONTADOR_ESTADO
	RJMP	FIN
MULTI_DISPLAY_3:
	LDI		R16,		0x04					// AQUI SUCEDE LO MISMO QUE ARRIBA, PERO CON OTRO TRANSISTOR
	OR		CONTADOR_ESTADO,	R16
	MOV		S_PORT,		CONTADOR_ESTADO
	RJMP	FIN
MULTI_DISPLAY_4:
	LDI		R16,		0x08					// AQUI SUCEDE LO MISMO QUE ARRIBA, PERO CON OTRO TRANSISTOR
	OR		CONTADOR_ESTADO,	R16
	MOV		S_PORT,		CONTADOR_ESTADO
	RJMP	FIN

APAGAR_DISPLAYS:
	LDI		R16,			0xF0				// SALTA AQUI CUANDO LA BANDERA DE APAGAR MULTI ESTA ENCENDIDA
	OUT		PORTB,			R16					// LO QUE HACE ES DIRECTAMENTE MANDAR UN VALOR A PORTB PARA APAGAR LOS TRANSISTORES

FIN:
	LDI		R16,			0x03				// AQUI INCREMENTA EL CONTADOR DE MULTIPLEXADO
	INC		CONTADOR_MULTI						// LUEGO LE HACE UNA MASCARA PARA QUE NO SE PASE DE 3
	AND		CONTADOR_MULTI,	R16
	POP		R16
	OUT		SREG,	R16
	POP		R16
	RETI
//----------------------------------------------------------------------------------------//
ISR_TMR1_OVF:
	PUSH	R16
	IN		R16,	SREG
	PUSH	R16
	// ----------------------------------------------------------------------------------- //
	LDI		R16,	HIGH(TCNT1_value)	// CARGA VALORES INICIALES DE TIMER 1
	STS		TCNT1H,	R16
	LDI		R16,	LOW(TCNT1_value)
	STS		TCNT1L,	R16
	// ----------------------------------------------------------------------------------- //
	LDI		R16,			0x80		// AQUI HACE EL PARPADEO DE LEDS
	IN		PARPADEO_LED,	PORTD		// OBTIENE EL VALOR DEL PORTD
	ANDI	PARPADEO_LED,	0X80		// LUEGO SOLO SE QUEDA CON EL BIT 7
	EOR		PARPADEO_LED,	R16			// Y HACE UN XOR PARA IR TOGGLEANDOLO, LUEGO LO JUNTAMOS EN LAS SALIDAS DE DISPLAY CON LOS VALORES DE
										// LA TABLA
	SBRC	BANDERA_ESTADO,	2			// AQUI REVISA SI LA BANDERA DE ALARMA CONFIGURADA ESTA ENCENDIDA, SI ES ASI
	RJMP	PARPADEO_LED_ALARMA			// SALTA A HACER PARPADEAR LOS LEDS DE LA ALARMA
	CBR		BANDERA_ESTADO, (1<<4)		// APAGA LA BANDERA DE APAGAR MULTIPLEXADO
	RJMP	CONTINUAR_TIMER1
	PARPADEO_LED_ALARMA:
	LDI		R16,			4			// AQUI VERIFICA QUE ESTE EN MODO SETEO DE ALARMA
	CP		MODO,			R16
	BRNE	APAGAR_PARPADEO				// SI NO, SE SALTA LA SIGUIENTE PARTE
	LDI		R16,			0x10		// LE CARGA 01 A R16
	EOR		BANDERA_ESTADO,	R16			// PARA HACER UN XOR CON LA BANDERA DE ESTADOS
	RJMP	CONTINUAR_TIMER1
	APAGAR_PARPADEO:
	CBR		BANDERA_ESTADO, (1<<4)		// AQUI LIMPIA LA BANDERA DE APAGAR MULTIPLEXADO
	RJMP	CONTINUAR_TIMER1
	// ----------------------------------------------------------------------------------- //
	CONTINUAR_TIMER1:
	LDI		ZL,		LOW(Cantidad_dias<<1)	// REINICIAMOS PUNTEROS DIAS
	LDI		ZH,		HIGH(Cantidad_dias<<1)
	ADD		ZL,		CONTADOR_MESES
	LPM		VARIABLE_DIAS,	Z
	// ----------------------------------------------------------------------------------- //
	SBRS	BANDERA_ESTADO,		0			// VERIFICA SI LA BANDERA DE PROSEGUIR CON EL CONTADOR ESTA ENCENDIDA
	RJMP	REGRESO_1
	// ----------------------------------------------------------------------------------- //
	INC		CONTADOR_TIEMPO					// AUMENTA CONTADOR CADA 500 ms
	CPI		CONTADOR_TIEMPO,	120			// COMPARA CONTADOR CON 120 PARA HACER 1 MIN
	BRNE	REGRESO_1
	CLR		CONTADOR_TIEMPO					// REINICIO DE CONTADOR DE TIEMPO
	// ------------------------------------- minutos ------------------------------------- //
	LDS		VARIABLE_TEMP_1,	VALOR_MIN_U		// LEE DE SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_MIN_D

	INC		VARIABLE_TEMP_1						// AUMENTO VALOR DE UNIDADES
	STS		VALOR_MIN_U,		VARIABLE_TEMP_1	// VA GUARDANDO CADA MODIFICACION
	CPI		VARIABLE_TEMP_1,	0x0A			// COMPARO CON 10
	BRNE	VERIFICAR_ALARMA
	CLR		VARIABLE_TEMP_1
	STS		VALOR_MIN_U,		VARIABLE_TEMP_1
	
	INC		VARIABLE_TEMP_2						// AUMENTO VALOR DE DECENAS
	STS		VALOR_MIN_D,		VARIABLE_TEMP_2
	CPI		VARIABLE_TEMP_2,	0x06			// COMPARO CON 6
	BRNE	VERIFICAR_ALARMA
	CLR		VARIABLE_TEMP_2
	STS		VALOR_MIN_D,		VARIABLE_TEMP_2

	// ------------------------------------- HORAS --------------------------------------- //
	LDS		VARIABLE_TEMP_1,	VALOR_HORA_U	// LEE DE SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_HORA_D

	CPI		VARIABLE_TEMP_2,	0x02		// COMPRUEBA SI ESTA EN LOS 20
	BREQ	CONTEO_2_HORAS

CONTEO_1_HORAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_HORA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	VERIFICAR_ALARMA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	STS		VALOR_HORA_U,		VARIABLE_TEMP_1 // GUARDA CADA CAMBIO
	RJMP	CONTEO_D_HORAS

CONTEO_2_HORAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_HORA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x04		// COMPARO CON 4
	BRNE	VERIFICAR_ALARMA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	STS		VALOR_HORA_U,		VARIABLE_TEMP_1
	RJMP	CONTEO_D_HORAS

CONTEO_D_HORAS:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	STS		VALOR_HORA_D,		VARIABLE_TEMP_2
	CPI		VARIABLE_TEMP_2,	0x03		// COMPARO CON 3
	BRNE	VERIFICAR_ALARMA				// DE AQUI SALTA A VERIFICAR LA ALARMA
	CLR		VARIABLE_TEMP_2					// REINICIO CONTADOR DE DECENAS
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	STS		VALOR_HORA_D,		VARIABLE_TEMP_2	// GUARDA EN SRAM
	STS		VALOR_HORA_U,		VARIABLE_TEMP_1
	RJMP	FECHA_TIMER
	
REGRESO_1:
	RJMP	REGRESO

VERIFICAR_ALARMA:
	SBRS    BANDERA_ESTADO,     2			// CUANDO VERIFICA LA ALARMA REVISA SI LA BANDERA DE ALARMA CONFIGURADA ESTA ENCENDIDA
    RJMP    REGRESO_ALARMA					// SI NO, SE SALTA ESTA PARTE
    LDS     VARIABLE_TEMP_1,    VALOR_MIN_U	// VA COMPARANDO VALOR POR VALOR
    LDS     VARIABLE_TEMP_2,    A_MIN_U
    CP      VARIABLE_TEMP_1,    VARIABLE_TEMP_2
    BRNE    REGRESO_ALARMA					// SI HAY ALGUNA DIFERENCIA SALE DE LA REVISION
    LDS     VARIABLE_TEMP_1,    VALOR_MIN_D
    LDS     VARIABLE_TEMP_2,    A_MIN_D
    CP      VARIABLE_TEMP_1,    VARIABLE_TEMP_2
    BRNE    REGRESO_ALARMA
    LDS     VARIABLE_TEMP_1,    VALOR_HORA_U
    LDS     VARIABLE_TEMP_2,    A_HORA_U
    CP      VARIABLE_TEMP_1,    VARIABLE_TEMP_2
    BRNE    REGRESO_ALARMA
    LDS     VARIABLE_TEMP_1,    VALOR_HORA_D
    LDS     VARIABLE_TEMP_2,    A_HORA_D
    CP      VARIABLE_TEMP_1,    VARIABLE_TEMP_2
    BRNE    REGRESO_ALARMA
ACTIVAR_BUZZER:
	SBR		BANDERA_ESTADO,		(1<<3)	// SI HAY UN MATCH, ENTONCES LO QUE HACE ES ENCENDER LA BANDER DE BUZZER
REGRESO_ALARMA:
	RJMP	REGRESO

FECHA_TIMER:
	// ------------------------------------- DIAS --------------------------------------- //
	LDS		VARIABLE_TEMP_1,	VALOR_DIA_U	// LEE DE SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_DIA_D

	CPI		VARIABLE_TEMP_2,	0x03		// COMPARA PARA VER SI ESTA EN 30
	BREQ	CONTADOR_3_DIAS
	CPI		VARIABLE_TEMP_2,	0x02		// COMPARA PARA VER SI ESTA EN 20
	BREQ	CONTADOR_2_DIAS

CONTADOR_1_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 2
	BRNE	REGRESO_3
	CLR		VARIABLE_TEMP_1
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	RJMP	CONTEO_D_DIAS

REGRESO_3:
	RJMP	REGRESO

CONTADOR_2_DIAS:
	LDI		R16,	28						// EN LOS 20, REVISA SI EL LIMITE DE DIAS ES 28
	CP		VARIABLE_DIAS,	R16
	BREQ	CONTEO_2_FEBRERO_DIAS			// SI ASI ES, ENTONCES SALTA A EL CONTADOR DE FEBRERO
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	REGRESO_2
	CLR		VARIABLE_TEMP_1
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	RJMP	CONTEO_D_DIAS
	CONTEO_2_FEBRERO_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x09		// COMPARO CON 9
	BRNE	REGRESO_2
	CLR		VARIABLE_TEMP_2					// REINICIA LOS CONTADORES
    LDI		VARIABLE_TEMP_1, 0x01
	STS		VALOR_DIA_D,		VARIABLE_TEMP_2	// GUARDA EN SRAM
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
    RJMP	REGRESO_2						// Y SALTA DIRECTAMENTE A SALIDA

CONTADOR_3_DIAS:
	LDI		R16,	31						// AQUI VERIFICA SI EL LIMITE ES 31
	CP		VARIABLE_DIAS,	R16
	BREQ	CONTEO_3_1_DIAS					// SI ASI ES, SALTA A SU CONTADOR RESPECTIVO
	LDI		R16,	30
	CP		VARIABLE_DIAS,	R16				// AQUI VERIFICA SI EL LIMITE ES 30
	BREQ	CONTEO_3_2_DIAS					// SI ASI ES, SALTA A SU CONTADOR RESPECTIVO
	RJMP	REGRESO_2
	CONTEO_3_1_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x02		// COMPARO CON 2
	BRNE	REGRESO_2
	CLR		VARIABLE_TEMP_1					// REINICIA VARIABLES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1 // Y LAS GUARDA
	RJMP	CONTEO_D_DIAS
	CONTEO_3_2_DIAS:
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	CPI		VARIABLE_TEMP_1,	0x01			// COMPARO CON 1
	BRNE	REGRESO_2
	CLR		VARIABLE_TEMP_1
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	RJMP	CONTEO_D_DIAS
	
CONTEO_D_DIAS:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	STS		VALOR_DIA_D,		VARIABLE_TEMP_2
	CPI		VARIABLE_TEMP_2,	0x04		// COMPARO CON 4
	BRNE	REGRESO_2
	CLR		VARIABLE_TEMP_2					// REINICIA CONTADOR DE DIAS EN DECENAS Y UNIDADES
	LDI		VARIABLE_TEMP_1,	0x01
	STS		VALOR_DIA_D,		VARIABLE_TEMP_2
	STS		VALOR_DIA_U,		VARIABLE_TEMP_1
	RJMP	FECHA_MES						// SALTA A MESES

REGRESO_2:
	RJMP	REGRESO

	// ------------------------------------- MESES --------------------------------------- //
FECHA_MES:
	LDS		VARIABLE_TEMP_1,	VALOR_MES_U	// LEE DE SRAM
	LDS		VARIABLE_TEMP_2,	VALOR_MES_D
	LDS		CONTADOR_MESES,		CONTEO_MESES
	CPI		VARIABLE_TEMP_2,	0x01		// REVISA PARA VER SI ESTA EN MESES 10, 11 O 12
	BREQ	CONTADOR_2_MESES

CONTADOR_1_MESES:
	INC		CONTADOR_MESES					// INCREMENTA EL CONTADOR DE MESES
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_MES_U,		VARIABLE_TEMP_1
	STS		CONTEO_MESES,		CONTADOR_MESES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	REGRESO
	CLR		VARIABLE_TEMP_1	
	STS		VALOR_MES_U,		VARIABLE_TEMP_1
	RJMP	CONTEO_D_MESES
CONTADOR_2_MESES:
	INC		CONTADOR_MESES					// INCREMENTA EL CONTADOR DE MESES
	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	STS		VALOR_MES_U,		VARIABLE_TEMP_1
	STS		CONTEO_MESES,		CONTADOR_MESES
	CPI		VARIABLE_TEMP_1,	0x03		// COMPARO CON 3
	BRNE	REGRESO
	LDI		VARIABLE_TEMP_1,	0x01
	LDI		R16,			0x01
	MOV		CONTADOR_MESES,	R16				// SI HACE OVERFLOW, LO REINICIA A 1
	STS		VALOR_MES_U,		VARIABLE_TEMP_1
	STS		CONTEO_MESES,		CONTADOR_MESES
	RJMP	CONTEO_D_MESES

CONTEO_D_MESES:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	STS		VALOR_MES_D,		VARIABLE_TEMP_2
	CPI		VARIABLE_TEMP_2,	0x02			// COMPARO CON 2
	BRNE	REGRESO
	CLR		VARIABLE_TEMP_2
	LDI		VARIABLE_TEMP_1,	0x01
	MOV		CONTADOR_MESES,	VARIABLE_TEMP_1
	STS		VALOR_MES_D,		VARIABLE_TEMP_2
	STS		VALOR_MES_U,		VARIABLE_TEMP_1
	STS		CONTEO_MESES,		CONTADOR_MESES

REGRESO:
	//-------------------------------------------------------------------------------------//
	POP		R16
	OUT		SREG,	R16
	POP		R16
	RETI
