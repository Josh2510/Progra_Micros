	LDS		VARIABLE_TEMP_1,	A_MIN_U		// LEO VALORES DE SRAM
	LDS		VARIABLE_TEMP_2,	A_MIN_D

	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x0A		// COMPARO CON 10
	BRNE	SALIDA_ALARMA_AUMENTO_MIN
	CLR		VARIABLE_TEMP_1					// REINICIO POR OVERFLOW

	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x06		// COMPARO CON 6
	BRNE	SALIDA_ALARMA_AUMENTO_MIN
	CLR		VARIABLE_TEMP_2					// REINICIO CONTADOR DE MINUTOS
SALIDA_ALARMA_AUMENTO_MIN:
	STS		A_MIN_U,	VARIABLE_TEMP_1		// GUARDO EN SRAM
	STS		A_MIN_D,	VARIABLE_TEMP_2
	RET
