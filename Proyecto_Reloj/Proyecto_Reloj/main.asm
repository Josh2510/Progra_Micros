	BRNE	SALIDA_ALARMA_DECREMENTO_MIN
	LDI		VARIABLE_TEMP_2,	0x05		// REINICIO POR UNDERFLOW
SALIDA_ALARMA_DECREMENTO_MIN:
	STS		A_MIN_U,	VARIABLE_TEMP_1
	STS		A_MIN_D,	VARIABLE_TEMP_2
	RET
