	CPI		VARIABLE_TEMP_1,	0x01			// SI LLEGA A 0 REVISA SI LAS UNIDADES ES 1
	BREQ	SALTO_TOPE							// PARA SALTAR HACIA EL MAXIMO DE DIAS

