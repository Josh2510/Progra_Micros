	CLR		CONTADOR_M_D
SALIDA_ALARMA_AUMENTO_MIN:
	STS		MOD_MIN_U,	CONTADOR_M_U
	STS		MOD_MIN_D,	CONTADOR_M_D
	RET

AUMENTO_HORA_ALARMA:
	CPI		CONTADOR_H_D,	0x02
	BREQ	C_A_2_HORAS

	INC		CONTADOR_H_U					// AUMENTO VALOR DE UNIDADES
