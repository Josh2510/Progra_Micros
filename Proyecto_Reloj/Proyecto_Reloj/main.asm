	INC		VARIABLE_TEMP_1					// AUMENTO VALOR DE UNIDADES
	CPI		VARIABLE_TEMP_1,	0x04		// COMPARO CON 4
	BRNE	SALIDA_ALARMA_AUMENTO_HORA
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
	RJMP	C_A_D_HORAS

C_A_D_HORAS:
	INC		VARIABLE_TEMP_2					// AUMENTO VALOR DE DECENAS
	CPI		VARIABLE_TEMP_2,	0x03		// COMPARO CON 6
	BRNE	SALIDA_ALARMA_AUMENTO_HORA
	CLR		VARIABLE_TEMP_2					// REINICIO CONTADOR DE DECENAS
	CLR		VARIABLE_TEMP_1					// REINICIO CONTADOR DE UNIDADES
SALIDA_ALARMA_AUMENTO_HORA:
	STS		A_HORA_U,	VARIABLE_TEMP_1		// GUARDO EN SRAM
	STS		A_HORA_D,	VARIABLE_TEMP_2
	RET
